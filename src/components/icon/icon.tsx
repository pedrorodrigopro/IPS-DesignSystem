export const Icon = ({ name, size = 20, className, style, ...rest }: IconProps) => {
  const SvgComponent = iconMap[name];

  if (!SvgComponent) {
    return null;
  }

  return (
    <SvgComponent
      width={size}
      height={size}
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
      // Allow CSS `color` to control the icon fill via currentColor.
      // This overrides hardcoded fill values baked into SVG paths when
      // the SVG root fill is set to currentColor — child paths without
      // an explicit fill inherit it; paths with explicit fills keep theirs
      // unless the SVG is authored with currentColor throughout.
      // For icons with hardcoded fills, consumers can wrap in a colored span
      // or use the className prop with a CSS `color` rule.
      {...rest}
    />
  );
};
